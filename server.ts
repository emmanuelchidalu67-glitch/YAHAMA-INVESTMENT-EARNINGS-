// Admin: Permanently Delete User Investment
const handlePermanentInvestmentDelete = (req: express.Request, res: express.Response) => {
  const { investmentId } = req.params;
  const refundCapital = req.body?.refundCapital === true || req.query.refundCapital === 'true';

  // Step 1: Immediately register in permanent deleted blacklist
  if (investmentId && !deletedInvestmentIds.includes(investmentId)) {
    deletedInvestmentIds.push(investmentId);
    try {
      if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });
      fs.writeFileSync(DELETED_INVESTMENTS_FILE, JSON.stringify(deletedInvestmentIds, null, 2), 'utf-8');
      if (!fs.existsSync(SRC_DATA_DIR)) fs.mkdirSync(SRC_DATA_DIR, { recursive: true });
      fs.writeFileSync(SRC_DELETED_INVS_FILE, JSON.stringify(deletedInvestmentIds, null, 2), 'utf-8');
    } catch (e) {
      console.error('Error writing deleted investments file:', e);
    }
  }

  const invIndex = db.investments.findIndex((i) => i.id === investmentId);
  const inv = invIndex !== -1 ? db.investments[invIndex] : null;
  const targetUserId = inv?.userId;
  const user = targetUserId ? findUserById(targetUserId) : null;

  if (user && inv) {
    // Optionally refund capital to user wallet balance
    if (refundCapital) {
      user.balance = Number(user.balance || 0) + Number(inv.capital || 0);
      db.transactions.push({
        id: `tx_ref_${Date.now()}_${Math.floor(1000 + Math.random() * 9000)}`,
        userId: user.id,
        userPhone: user.phone,
        type: 'deposit',
        amount: inv.capital,
        status: 'approved',
        paymentMethod: 'Capital Refund (Admin)',
        proofReference: `REFUND-${inv.id}`,
        adminNote: `Admin Capital Refund for Deleted Plan "${inv.planName}"`,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
        creditedAt: new Date().toISOString(),
      });
    }

    // Decrement user's total invested capital safely
    user.totalInvested = Math.max(0, Number(user.totalInvested || 0) - Number(inv.capital || 0));

    // Recalculate user VIP Level based on their remaining active investments
    const remainingActive = db.investments.filter(
      (i) => i.userId === user.id && i.id !== inv.id && !deletedInvestmentIds.includes(i.id) && i.status === 'active'
    );
    if (remainingActive.length > 0) {
      const maxVip = Math.max(...remainingActive.map((i) => i.planLevel));
      user.vipLevel = Math.max(1, maxVip) as any;
    } else {
      user.vipLevel = 1;
    }
  }

  // Permanently remove the investment product from system database & memory
  db.investments = db.investments.filter((i) => i.id !== investmentId && !deletedInvestmentIds.includes(i.id));
  db.deletedInvestmentIds = deletedInvestmentIds;
  saveDB(db);

  return res.json({
    success: true,
    message: inv
      ? `Investment "${inv.planName}" (ID: ${inv.id}) for user ${inv.userPhone || user?.phone} has been PERMANENTLY DELETED from system memory and disk storage.`
      : `Investment ID ${investmentId} has been permanently removed from all databases.`,
    deletedInvestmentId: investmentId,
    deletedInvestmentIds,
    investments: db.investments,
    user: user || null,
    users: db.users,
  });
};

