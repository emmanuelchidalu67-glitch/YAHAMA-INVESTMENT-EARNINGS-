function saveDB(dbData: DatabaseSchema) {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }

    // Always include current deletedInvestmentIds in the payload
    dbData.deletedInvestmentIds = deletedInvestmentIds;

    const jsonString = JSON.stringify(dbData, null, 2);
    const tempFile = path.join(DATA_DIR, `db.tmp.${Date.now()}.${Math.random().toString(36).substring(2, 6)}`);

    // Step 1: Write to temporary file
    fs.writeFileSync(tempFile, jsonString, 'utf-8');

    // Step 2: Atomic rename to primary db.json
    fs.renameSync(tempFile, DB_FILE);

    // Step 3: Write secondary safety backups
    try {
      fs.writeFileSync(DB_BACKUP_FILE, jsonString, 'utf-8');
      fs.writeFileSync(DB_SNAPSHOT_FILE, jsonString, 'utf-8');
    } catch (bErr) {
      console.warn('Backup mirror write warning:', bErr);
    }

    // Step 4: Standalone dedicated permanent append files
    try {
      fs.writeFileSync(PERMANENT_USERS_FILE, JSON.stringify(dbData.users, null, 2), 'utf-8');
      fs.writeFileSync(PERMANENT_TX_FILE, JSON.stringify(dbData.transactions, null, 2), 'utf-8');
      fs.writeFileSync(PERMANENT_INV_FILE, JSON.stringify(dbData.investments, null, 2), 'utf-8');
      fs.writeFileSync(DELETED_INVESTMENTS_FILE, JSON.stringify(deletedInvestmentIds, null, 2), 'utf-8');
    } catch (pErr) {
      console.warn('Permanent sub-ledger write warning:', pErr);
    }

    // Step 5: Standalone dedicated admin_settings.json persistence
    try {
      const settingsJson = JSON.stringify(dbData.adminSettings, null, 2);
      fs.writeFileSync(SETTINGS_FILE, settingsJson, 'utf-8');
      fs.writeFileSync(SETTINGS_BACKUP_FILE, settingsJson, 'utf-8');
    } catch (sErr) {
      console.warn('Standalone settings write warning:', sErr);
    }

    // Step 6: Multi-layer persistence complete with zero TSX dev server reloads
    lastDbSaveTimestamp = new Date().toISOString();
  } catch (err) {
    console.error('CRITICAL: Error during atomic database write to disk:', err);
  }
}

